-- THE FRIENDS CLUB — Supabase database setup
-- Run this entire script once in Supabase SQL Editor.
-- Public read/insert is enabled because this website intentionally has no login.
-- Do not store private or sensitive information in this public memory wall.

create table if not exists public.friends_memories (
  id bigint generated by default as identity primary key,
  author text not null check (char_length(author) between 1 and 50),
  content text not null check (char_length(content) between 1 and 1200),
  created_at timestamptz not null default now()
);

alter table public.friends_memories enable row level security;

drop policy if exists "Public can view memories" on public.friends_memories;
create policy "Public can view memories"
on public.friends_memories for select to anon
using (true);

drop policy if exists "Public can add memories" on public.friends_memories;
create policy "Public can add memories"
on public.friends_memories for insert to anon
with check (
  char_length(author) between 1 and 50
  and char_length(content) between 1 and 1200
);

grant select, insert on public.friends_memories to anon;
grant usage, select on sequence public.friends_memories_id_seq to anon;
